"""Rebuild numerical combat metadata from the pinned primary database.
Run with --fetch to refresh the local input cache (requires PyYAML).
"""
import json,subprocess,sys,urllib.request
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
PIN='d4b8e7b8f16061cc2496d377ac8f777ce72a4f39'
cache=ROOT/'outputs/ro-skill-db-cache.json'
if '--fetch' in sys.argv:
 import yaml
 data=urllib.request.urlopen('https://raw.githubusercontent.com/rathena/rathena/'+PIN+'/db/re/skill_db.yml',timeout=60).read().decode()
 cache.parent.mkdir(exist_ok=True);cache.write_text(json.dumps(yaml.safe_load(data)['Body']),encoding='utf-8')
keys=set(json.loads(subprocess.check_output(['node','--input-type=module','-e',"import{RO_SKILLS}from'./shared/ragnarok-jobs.js';import{roSkillSource}from'./shared/ro-skill-source.js';console.log(JSON.stringify(Object.values(RO_SKILLS).map(roSkillSource)))"],cwd=ROOT,text=True)))
def values(value,field='Time'):
 if not isinstance(value,list):return value or 0
 return [v.get(field,0) for v in sorted(value,key=lambda v:v['Level'])]
rows={d['Name']:{'cooldown':values(d.get('Cooldown')),'afterCast':values(d.get('AfterCastActDelay')),'hits':values(d.get('HitCount',1),'Count'),'category':{'Weapon':'physical','Magic':'magic','Misc':'misc'}.get(d.get('Type'),'physical'),'element':d.get('Element','Neutral'),'noDamage':bool(d.get('DamageFlags',{}).get('NoDamage'))} for d in json.loads(cache.read_text(encoding='utf-8')) if d['Name'] in keys}
(ROOT/'shared/ro-native-skill-data.js').write_text('// Numerical facts from rAthena '+PIN+'; generated by scripts/import-ro-native-combat.py.\nexport const RO_NATIVE_SKILL_DATA=Object.freeze('+json.dumps(rows,separators=(',',':'))+');\n',encoding='utf-8')
print('Native skill records:',len(rows))
