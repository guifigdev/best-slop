"""Import race/property/size modifiers from the pinned rAthena item database.

Refine-only gates are intentionally lifted for our game. Skill, level, set and
autocast conditions are not treated as unconditional equipment bonuses.
"""
import json,re,subprocess,yaml
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
rows=yaml.safe_load((ROOT/'outputs/ro-build-item-db.yml').read_text(encoding='utf-8'))['Body']
ids=set(json.loads(subprocess.check_output(['node','--input-type=module','-e',"import{RO_EQUIPMENT}from'./shared/ragnarok-equipment.js';console.log(JSON.stringify(Object.values(RO_EQUIPMENT).map(d=>d.sourceId)))"],cwd=ROOT,text=True)))
families={'bAddRace':'raceDamage','bMagicAddRace':'magicRaceDamage','bSubRace':'raceResistance','bAddEle':'targetElementDamage','bMagicAddEle':'magicTargetElementDamage','bAddSize':'sizeDamage','bMagicAddSize':'magicSizeDamage','bSubSize':'sizeResistance','bMagicAtkEle':'elementalPower','bSubEle':'elementalResistance'}
keys={'DemiHuman':'demihuman','Player_Human':'human','Brute':'brute','Insect':'insect','Plant':'plant','Undead':'undead','Demon':'demon','Formless':'formless','Fish':'fish','Angel':'angel','Dragon':'dragon','Neutral':'neutral','Water':'water','Earth':'earth','Fire':'fire','Wind':'wind','Poison':'poison','Holy':'holy','Dark':'dark','Ghost':'ghost','Small':'small','Medium':'medium','Large':'large','All':'all'}
facts={};audit=[]
for row in rows:
 if row['Id'] not in ids:continue
 script=row.get('Script','');stack=[];single=None;result={};skipped=[]
 # Local adaptation of a few refine-dependent expressions, verified in source.
 expressions={1377:{'10+.@r':22},28136:{'.@red':25},19482:{'5*(.@r/4)':15}}
 for line in script.splitlines():
  line=line.strip()
  if line.startswith('}'):
   if stack:stack.pop()
  if line.startswith('if ' ) or line.startswith('if('):
   refine=bool(re.search(r'getrefine\(|\.@r\s*[><=]',line))
   if '{' in line:stack.append(refine)
   else:single=refine
   continue
  matches=list(re.finditer(r'bonus2\s+(\w+),\s*(?:RC_|Ele_|Size_)(\w+),\s*([^;]+);',line))
  for match in matches:
   command,key,expression=match.groups()
   if command not in families or key not in keys:continue
   # Quoted autobonus scripts are temporary procs, not permanent gear stats.
   allowed=all(stack) and single is not False and not line.startswith(('autobonus','bonus3','bonus4'))
   number=float(expression) if re.fullmatch(r'-?\d+(?:\.\d+)?',expression) else expressions.get(row['Id'],{}).get(expression)
   if not allowed or number is None:skipped.append(match.group(0));continue
   family=families[command];target=result.setdefault(family,{});target[keys[key]]=round(target.get(keys[key],0)+number/100,6)
  if line and not line.startswith(('//','}')):single=None
 if result:facts[row['Id']]=result
 if result or skipped:audit.append({'id':row['Id'],'name':row['Name'],'imported':result,'conditionalOrUnsupported':skipped})
source='https://github.com/rathena/rathena/blob/d4b8e7b8f16061cc2496d377ac8f777ce72a4f39/db/re/item_db_equip.yml'
(ROOT/'shared/ro-equipment-target-facts.js').write_text('// Generated by scripts/import-ro-equipment-targets.py. Refine gates lifted; other conditions retained.\nexport const RO_EQUIPMENT_TARGET_SOURCE='+json.dumps(source)+';\nexport const RO_EQUIPMENT_TARGET_FACTS=Object.freeze('+json.dumps(facts,separators=(',',':'))+');\n',encoding='utf-8')
(ROOT/'outputs/equipment-target-audit.json').write_text(json.dumps({'source':source,'items':audit},ensure_ascii=False,indent=2),encoding='utf-8')
print('Imported',len(facts),'equipment definitions; audit outputs/equipment-target-audit.json')
