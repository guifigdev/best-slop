"""Generate factual monster size/race/element multipliers from cached LATAM pages."""
import html,json,re,unicodedata,sys,subprocess,urllib.request,time
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
if '--fetch' in sys.argv:
 ids=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import{RO_MONSTER_PROPERTIES}from'./shared/ro-monster-properties-data.js';console.log(JSON.stringify(Object.keys(RO_MONSTER_PROPERTIES)))"],cwd=ROOT,text=True));cache=ROOT/'outputs/ro-latam-monsters';cache.mkdir(parents=True,exist_ok=True)
 for id in ids:
  file=cache/(id+'.html')
  if file.exists():continue
  request=urllib.request.Request('https://latamro.com/monstro/'+id+'/',headers={'User-Agent':'CustomHeroSourceImporter/1.0'})
  with urllib.request.urlopen(request,timeout=60) as response:file.write_text(response.read().decode('utf-8'),encoding='utf-8')
  time.sleep(.5)
plain=lambda s:html.unescape(re.sub('<[^>]+>','',s)).strip()
def norm(s):return ''.join(c for c in unicodedata.normalize('NFD',s.lower()) if unicodedata.category(c)!='Mn')
elements={'neutro':'neutral','agua':'water','terra':'earth','fogo':'fire','vento':'wind','veneno':'poison','sagrado':'holy','sombrio':'dark','fantasma':'ghost','morto-vivo':'undead'}
rows={}
for file in (ROOT/'outputs/ro-latam-monsters').glob('*.html'):
 s=file.read_text(encoding='utf-8');fields={norm(plain(k)):plain(v) for k,v in re.findall(r'<dt\b[^>]*>(.*?)</dt>\s*<dd\b[^>]*>(.*?)</dd>',s,re.S)}
 element=norm(fields.get('elemento',''));m=re.match(r'(.+?)\s+(\d)',element)
 if not m:raise ValueError(file)
 resist={elements[norm(name)]:float(value.replace(',','.'))/100 for name,value in re.findall(r'<span class="so-leitor"[^>]*>([^:<]+):\s*([\d,-]+)%',s) if norm(name) in elements}
 for name in re.findall(r'<span class="so-leitor"[^>]*>([^:<]+):\s*imune',s):
  if norm(name) in elements:resist[elements[norm(name)]]=0
 if len(resist)!=10:raise ValueError((file,len(resist)))
 rows[file.stem]={'name':fields.get('nome',''),'level':int(fields.get('nivel','1').replace('.','')),'race':fields.get('raca',''),'size':{'pequeno':'small','medio':'medium','grande':'large'}[norm(fields['tamanho'])],'element':elements[m[1]],'elementLevel':int(m[2]),'multipliers':resist,'defense':int(fields.get('def','0').replace('.','')),'magicDefense':int(fields.get('def magica','0').replace('.','')),'source':'https://latamro.com/monstro/'+file.stem+'/'}
(ROOT/'shared/ro-monster-properties-data.js').write_text('// Numerical facts from Ragnarok LATAM monster pages; generated by scripts/import-ro-latam-monsters.py.\nexport const RO_MONSTER_PROPERTIES=Object.freeze('+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+');\n',encoding='utf-8')
print('LATAM classifications:',len(rows))
