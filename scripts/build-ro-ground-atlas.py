"""Pack original item PNGs without resampling. Runtime uses one bounded draw."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
sources = sorted((root / 'src/assets/ro-equipment-icons').glob('*.png'))
sources += sorted((root / 'src/assets/ro-ground-icons').glob('*.png'))
atlas = Image.new('RGBA', (1024, 1024))
frames = {}
for index, file in enumerate(sources):
    image = Image.open(file).convert('RGBA')
    if image.width > 32 or image.height > 32:
        raise ValueError(f'Unexpected native icon dimensions: {file}')
    x, y = (index % 16) * 36 + 2, (index // 16) * 36 + 2
    atlas.paste(image, (x + (32-image.width)//2, y + (32-image.height)//2))
    frames[file.stem] = [x/1024, 1-(y+32)/1024, 32/1024, 32/1024]
dest = root / 'src/assets/ro-ground-icons'
atlas.save(dest / 'items-atlas.png', optimize=True)
(dest / 'PROVENANCE.txt').write_text('Original Ragnarok item pixels, from installed data.grf. Artwork belongs to Gravity. Equipment provenance: ../ro-equipment-icons/manifest.json. Potions: item IDs 501 and 505. Atlas introduces no resampling.\n', encoding='utf8')
(root / 'src/ro-ground-icon-atlas.js').write_text('// Generated by scripts/build-ro-ground-atlas.py.\nexport const RO_GROUND_ICON_ATLAS=new URL(\'./assets/ro-ground-icons/items-atlas.png\',import.meta.url).href;\nexport const RO_GROUND_ICON_FRAMES=Object.freeze('+json.dumps(frames,separators=(',', ':'))+');\n', encoding='utf8')
print(f'Packed {len(frames)} native item sprites into one atlas')
