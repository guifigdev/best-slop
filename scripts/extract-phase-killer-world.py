"""Extract numeric scenery from the pinned Phase Killer map; no native art is copied."""
from pathlib import Path
import hashlib
import importlib.util
import json
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'outputs/phase-killer-reference/original'
EXPECTED = {'war3map.w3e': '4bb8889159c6801ac9ceab16806a08e8add086aa6d1ecb86b84ebbb5320297bd',
            'war3map.doo': 'e2ff05416d54811115c967a7bea33216000eeaae60706c960e6a5aa9cace53dc'}
files = {name: (SOURCE/name).read_bytes() for name in EXPECTED}
for name, data in files.items():
    if hashlib.sha256(data).hexdigest() != EXPECTED[name]:
        raise ValueError('Unexpected source: '+name)
spec = importlib.util.spec_from_file_location('terrain_reader', ROOT/'scripts/extract-warcraft-terrain.py')
reader = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reader)
terrain = reader.read_w3e(files['war3map.w3e'])
data = files['war3map.doo']
if data[:4] != b'W3do' or struct.unpack_from('<II', data, 4) != (8, 11):
    raise ValueError('Unsupported doodad format')
count, = struct.unpack_from('<I', data, 12)
offset = 16
identifiers = ['JTtw', 'JTct', 'LRrk', 'VSvb', 'YOlp', 'YOfn', 'YSaw', 'YOks', 'YTpc', 'YSca', 'JOgr', 'LOpg', 'LOgr']
placements = []
for index in range(count):
    raw = data[offset:offset+4].decode('ascii')
    variation, x, y, z, angle, sx, sy, sz, flags, life, table, sets = struct.unpack_from('<IfffffffBBiI', data, offset+4)
    offset += 46
    for _ in range(sets):
        items, = struct.unpack_from('<I', data, offset)
        offset += 4+items*8
    offset += 4  # editor ID
    if raw in identifiers:
        placements.append([identifiers.index(raw), round(x/128, 3), round(-y/128, 3), round(sx, 3), round(angle, 3), variation])
if offset+8 != len(data):
    raise ValueError('Unexpected doodad trailer')
result = dict(provenance=dict(map='Phase Killer 1.2.8', hashes=EXPECTED, coordinates='x=nativeX/128,z=-nativeY/128',
                             nativeDoodads=count, note='Numeric positions and terrain IDs only; voxel models are original browser art.'),
              width=terrain['width'], height=terrain['height'], origin=[terrain['offset'][0]/128, -terrain['offset'][1]/128],
              textures=terrain['ground'], tiles=''.join(format(v['texture'], 'x') for v in terrain['vertices']),
              # Quantized height only tints the level playable surface; no false 3D pathing equivalence.
              relief=''.join(format(max(0, min(15, round(v['height']/128))), 'x') for v in terrain['vertices']),
              identifiers=identifiers, placements=placements)
destination = ROOT/'shared/phase-killer-terrain-data.js'
destination.write_text('// Generated by scripts/extract-phase-killer-world.py from verified numeric map data.\nexport const PHASE_TERRAIN_DATA=Object.freeze('+json.dumps(result, separators=(',', ':'))+');\n', encoding='utf8')
print(f'{destination.name}: {len(placements)} placements, {terrain["width"]}x{terrain["height"]} terrain vertices')
