import {writeFileSync} from 'node:fs';
import {ragnarokMonsterSpec} from '../src/ragnarok-monster-art.js';
import {RAGNAROK_VOXEL_REFERENCES} from '../shared/monster-visual-references.js';
// Project the lower living body and feet, excluding high wings, weapons and
// horns. Store measurements, so the server never imports rendering modules.
export function measureRoBody(spec){
 const height=Math.max(...spec.parts.map(p=>p[1]+p[4]/2));
 const body=spec.parts.filter(p=>p[1]-p[4]/2<height*.55&&p[1]+p[4]/2>.08);
 return Math.max(.2,...body.map(p=>Math.hypot(Math.abs(p[0])+p[3]/2,Math.abs(p[2])+p[5]/2)),...(spec.legs||[]).map(p=>Math.hypot(Math.abs(p.x)+p.w/2,Math.abs(p.z)+p.d/2)));
}
export function measureRoBodyHull(spec){
 const height=Math.max(...spec.parts.map(p=>p[1]+p[4]/2)),points=[];
 for(const p of spec.parts.filter(p=>p[1]-p[4]/2<height*.55&&p[1]+p[4]/2>.08))for(const x of [-1,1])for(const z of [-1,1])points.push([p[0]+x*p[3]/2,p[2]+z*p[5]/2]);
 for(const p of spec.legs||[])for(const x of [-1,1])for(const z of [-1,1])points.push([p.x+x*p.w/2,p.z+z*p.d/2]);
 points.sort((a,b)=>a[0]-b[0]||a[1]-b[1]);const cross=(a,b,c)=>(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0]);
 const chain=points=>{const out=[];for(const p of points){while(out.length>1&&cross(out.at(-2),out.at(-1),p)<=0)out.pop();out.push(p);}return out.slice(0,-1);};
 return [...chain(points),...chain(points.slice().reverse())].map(p=>p.map(v=>Number(v.toFixed(5))));
}
const facts={},hulls={};for(const key of Object.keys(RAGNAROK_VOXEL_REFERENCES)){const s=ragnarokMonsterSpec(key);if(s){facts[key]=Math.ceil(measureRoBody(s)*10000)/10000;hulls[key]=measureRoBodyHull(s);}}
writeFileSync(new URL('../shared/ro-monster-footprints.js',import.meta.url),'// Generated by scripts/build-ro-footprints.mjs from the actual volumetric models.\nexport const RO_MONSTER_BODY_RADII=Object.freeze('+JSON.stringify(facts)+');\nexport const roMonsterBodyRadius=unit=>Math.max(.2,Math.min(4,(RO_MONSTER_BODY_RADII[unit.ragnarokVisual]||.45)*(unit.size||1)));\n');
console.log('Measured '+Object.keys(facts).length+' monster bodies.');

writeFileSync(new URL('../shared/ro-monster-body-hulls.js',import.meta.url),'// Generated lower-body convex hulls; x/z metres before actor scale and facing.\nexport const RO_MONSTER_BODY_HULLS=Object.freeze('+JSON.stringify(hulls)+');\n');
