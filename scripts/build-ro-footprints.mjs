import {writeFileSync} from 'node:fs';
import {ragnarokMonsterSpec} from '../src/ragnarok-monster-art.js';
import {RAGNAROK_VOXEL_REFERENCES} from '../shared/monster-visual-references.js';
// Project the lower living body and feet, excluding high wings, weapons and
// horns. Store measurements, so the server never imports rendering modules.
export function measureRoBody(spec){
 const height=Math.max(...spec.parts.map(p=>p[1]+p[4]/2));
 const body=spec.parts.filter(p=>p[1]-p[4]/2<height*.55&&p[1]+p[4]/2>.08);
 return Math.max(.2,...body.map(p=>Math.hypot(Math.abs(p[0])+p[3]/2,Math.abs(p[2])+p[5]/2)),...(spec.legs||[]).map(p=>Math.hypot(Math.abs(p.x)+p.w/2,Math.abs(p.z)+p.d/2)));
}
const facts={};for(const key of Object.keys(RAGNAROK_VOXEL_REFERENCES)){const s=ragnarokMonsterSpec(key);if(s)facts[key]=Math.ceil(measureRoBody(s)*10000)/10000;}
writeFileSync(new URL('../shared/ro-monster-footprints.js',import.meta.url),'// Generated by scripts/build-ro-footprints.mjs from the actual volumetric models.\nexport const RO_MONSTER_BODY_RADII=Object.freeze('+JSON.stringify(facts)+');\nexport const roMonsterBodyRadius=unit=>Math.max(.2,Math.min(4,(RO_MONSTER_BODY_RADII[unit.ragnarokVisual]||.45)*(unit.size||1)));\n');
console.log('Measured '+Object.keys(facts).length+' monster bodies.');
