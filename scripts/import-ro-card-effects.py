"""Keep the original card bonus DSL as data; no executable client scripts."""
import json
import re
import subprocess
from urllib.request import urlopen
from pathlib import Path

root = Path(__file__).resolve().parents[1]
ids = set(json.loads(subprocess.check_output(
    ['node', '--input-type=module', '-e', "import {RO_CARDS} from './shared/ragnarok-equipment.js'; console.log(JSON.stringify(Object.values(RO_CARDS).map(c=>c.sourceId)))"],
    cwd=root, text=True, encoding='utf8')))
source_path = root / 'outputs/ro-card-item-db.yml'
if not source_path.exists():
    source_path.parent.mkdir(parents=True, exist_ok=True)
    source_path.write_bytes(urlopen('https://raw.githubusercontent.com/rathena/rathena/master/db/re/item_db_etc.yml', timeout=60).read())
source = source_path.read_text(encoding='utf8')
records = {}
for block in re.split(r'^  - Id: ', source, flags=re.M)[1:]:
    item_id = int(block.splitlines()[0])
    if item_id not in ids:
        continue
    script = re.search(r'^    Script: \|\n((?:      .*\n|\n)*)', block, re.M)
    if script:
        records[str(item_id)] = {'Script': '\n'.join(line[6:] for line in script[1].splitlines())}
(root / 'shared/ro-card-native-data.js').write_text(
    '// Source: https://github.com/rathena/rathena/blob/master/db/re/item_db_etc.yml\n'
    '// Generated by scripts/import-ro-card-effects.py; original numeric bonus scripts.\n'
    'export const RO_CARD_NATIVE=Object.freeze(' + json.dumps(records, ensure_ascii=False, separators=(',', ':')) + ');\n', encoding='utf8')
print(f'Imported {len(records)} card scripts')
