"""Generate factual weapon overrides from the pinned map objects and base SLK export.

Inputs are kept in outputs/castle-original. Base SLK provenance is recorded in
docs/CASTLE_FIGHT_REFERENCE.md; explicit map fields always take precedence.
"""
import json, pathlib, subprocess

root = pathlib.Path(__file__).resolve().parents[1]
source = root / 'outputs/castle-original'
objects = {v['id']: v for v in json.loads((source/'war3map.w3u.json').read_text())}
base = json.loads((source/'base-weapons.json').read_text())
keys = json.loads(subprocess.check_output(['node','--input-type=module','-e',
    "import {CASTLE_UNITS,CASTLE_BUILDINGS} from './shared/castle-catalog.js'; console.log(JSON.stringify([...new Set([...Object.keys(CASTLE_UNITS),...Object.values(CASTLE_BUILDINGS).filter(b=>b.castleEffect?.type==='tower').map(b=>b.rawId)])]));"],cwd=root,text=True))
result = {}
for key in keys:
    obj=objects.get(key,{}); fields=obj.get('fields',{}); inherited=base.get(obj.get('base',key),{})
    def value(field,column,default=None):
        v=fields.get(field,inherited.get(column,default))
        return default if v in ('-','_',None,'') else v
    enabled=int(value('uaen','weapsOn',1)); weapons=[]
    for slot in (1,2):
        if not enabled & slot: continue
        targets=str(value(f'ua{slot}g',f'targs{slot}','')).split(',')
        rng=float(value(f'ua{slot}r',f'rangeN{slot}',0))
        if not targets or not rng: continue
        damage=float(value(f'ua{slot}b',f'dmgplus{slot}',0))+float(value(f'ua{slot}d',f'dice{slot}',1))*(float(value(f'ua{slot}s',f'sides{slot}',1))+1)/2
        weapons.append(dict(slot=slot,targets=targets,range=round(max(.55,rng/256),6),interval=float(value(f'ua{slot}c',f'cool{slot}',1.5)),damage=damage,attackType=value(f'ua{slot}t',f'atkType{slot}','normal')))
    result[key]=weapons
(root/'shared/castle-weapon-data.js').write_text('// Generated by scripts/audit-castle-weapons.py. Map overrides + inherited base weapon fields.\nexport const CASTLE_WEAPON_DATA='+json.dumps(result,separators=(',',':'))+';\n')
print(f'Audited {len(result)} unit/tower profiles; {sum(len(w)>1 for w in result.values())} dual weapons.')
