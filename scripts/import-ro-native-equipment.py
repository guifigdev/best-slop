"""Rebuild native equipment facts and audit explicit LATAM base values.

Uses cached primary database rows and LATAM client descriptions in outputs/.
--fetch refreshes the pinned database input (requires PyYAML).
Bonus instructions remain source data, interpreted by ro-equipment-native.js.
"""
import html,json,re,subprocess,sys,unicodedata,urllib.request
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
PIN='d4b8e7b8f16061cc2496d377ac8f777ce72a4f39'
cache=ROOT/'outputs/native-gear-audit-input.json'
if '--fetch' in sys.argv:
 import yaml
 ids=set(json.loads(subprocess.check_output(['node','--input-type=module','-e',"import{RO_EQUIPMENT}from'./shared/ragnarok-equipment.js';console.log(JSON.stringify(Object.values(RO_EQUIPMENT).map(d=>d.sourceId)))"],cwd=ROOT,text=True)))
 data=urllib.request.urlopen('https://raw.githubusercontent.com/rathena/rathena/'+PIN+'/db/re/item_db_equip.yml',timeout=60).read().decode()
 cache.parent.mkdir(exist_ok=True);cache.write_text(json.dumps([d for d in yaml.safe_load(data)['Body'] if d['Id'] in ids]),encoding='utf-8')
normal=lambda text:''.join(c for c in unicodedata.normalize('NFD',text) if unicodedata.category(c)!='Mn')
fields=['Attack','MagicAttack','Defense','WeaponLevel','EquipLevelMin','Script']
labels={'Attack':r'ATQ','MagicAttack':r'ATQM','Defense':r'Defesa','WeaponLevel':r'Nivel da arma','EquipLevelMin':r'Nivel necessario'}
rows={};audit=[]
for d in json.loads(cache.read_text(encoding='utf-8')):
 row={k:d[k] for k in fields if k in d};file=ROOT/f"outputs/ro-equipment-latam/{d['Id']}.html";differences={}
 if file.exists():
  match=re.search(r'class="descricao"[^>]*>(.*?)</div>',file.read_text(encoding='utf-8'),re.S)
  if match:
   description=normal(html.unescape(re.sub('<[^>]+>',' ',match[1])))
   for key,label in labels.items():
    found=re.findall(r'\b'+label+r'\s*:\s*(\d+)',description,re.I)
    if found:
     value=int(found[-1])
     if row.get(key,0)!=value:differences[key]={'pinned':row.get(key,0),'latam':value}
     row[key]=value
 rows[str(d['Id'])]=row
 audit.append({'id':d['Id'],'latamPageCached':file.exists(),'baseDifferences':differences})
(ROOT/'shared/ro-equipment-native-data.js').write_text('// Native numerical facts and restricted bonus instructions; generated by scripts/import-ro-native-equipment.py.\nexport const RO_EQUIPMENT_NATIVE=Object.freeze('+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+');\n',encoding='utf-8')
(ROOT/'outputs/ro-native-latam-base-audit.json').write_text(json.dumps({'pinned':PIN,'items':audit},ensure_ascii=False,indent=2),encoding='utf-8')
print('Native equipment:',len(rows),'LATAM pages:',sum(r['latamPageCached'] for r in audit),'base differences:',sum(bool(r['baseDifferences']) for r in audit))
