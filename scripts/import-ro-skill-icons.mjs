import {writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {openRoArchive} from './ro-client-archive.mjs';
import {png} from './ro-client-bmp.mjs';
import {RO_SKILLS} from '../shared/ragnarok-jobs.js';
import {roSkillSource} from '../shared/ro-skill-source.js';
const client=process.argv[2]||'C:/Gravity/Ragnarok',archive=openRoArchive(path.join(client,'data.grf')),out='src/assets/ro-skill-icons';
await mkdir(out,{recursive:true});
try{
 const records={},mapping={},missing=[];
 for(const [key,skill]of Object.entries(RO_SKILLS)){
  const source=roSkillSource({...skill,key}).toLowerCase(),resource='data/texture/유저인터페이스/item/'+source+'.bmp',bytes=archive.read(resource);
  if(!bytes){missing.push(key);continue;}
  if(!records[source]){const image=png(bytes);await writeFile(path.join(out,source+'.png'),image.data);records[source]={resource,width:image.width,height:image.height,sha256:createHash('sha256').update(image.data).digest('hex')};}
  mapping[key]=source;
 }
 await writeFile(path.join(out,'manifest.json'),JSON.stringify({source:'Original installed Ragnarok client: data.grf',records,mapping,missing},null,2)+'\n');
 await writeFile(path.join(out,'PROVENANCE.txt'),'Original Ragnarok skill icons extracted read-only from data.grf. Artwork belongs to Gravity. Original pixels retained; magenta transparency converted to PNG alpha. Custom skills use separate authored pixel drawings.\n');
 await writeFile('src/ro-skill-icon-assets.js','// Generated by scripts/import-ro-skill-icons.mjs.\nconst assets={\n'+Object.keys(records).map(key=>JSON.stringify(key)+':new URL(\'./assets/ro-skill-icons/'+key+'.png\',import.meta.url).href').join(',\n')+'\n};\nexport const RO_SKILL_ICON_ASSETS=Object.freeze('+JSON.stringify(mapping)+');\nexport const roOriginalSkillIcon=key=>assets[RO_SKILL_ICON_ASSETS[key]]||null;\n');
 console.log(JSON.stringify({skills:Object.keys(mapping).length,uniqueIcons:Object.keys(records).length,missing}));
}finally{archive.close();}
